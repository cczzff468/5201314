/** 按当前模式转换正文（逐字查表，未收录原样保留；换行保持） */
export function convertLang(text: string, mode: LangMode): string {
  if (!mode || mode === 'off' || !text) return text;
  const map = mode === 's2t' ? S2T : T2S;
  let out = '';
  for (const ch of text) out += map[ch] ?? ch;
  return out;
}
